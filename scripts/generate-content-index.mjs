import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import ts from 'typescript'

const root = process.cwd()
const storePath = path.join(root, 'src', 'data', 'contentStore.ts')
const outPath = path.join(root, 'src', 'data', 'contentIndex.ts')

const sectionOrderByLevel = {
  STARTER: ['orientation', 'kana', 'phrases', 'sentences', 'study'],
  N5: ['overview', 'vocab', 'kanji', 'grammar', 'listening', 'reading', 'tests'],
  N4: ['overview', 'vocab', 'kanji', 'grammar', 'listening', 'reading', 'tests'],
  N3: ['overview', 'vocab', 'kanji', 'grammar', 'listening', 'reading', 'tests'],
  N2: ['overview', 'vocab', 'kanji', 'grammar', 'listening', 'reading', 'tests'],
  N1: ['overview', 'vocab', 'kanji', 'grammar', 'listening', 'reading', 'tests'],
}

function toModuleLiteral(value) {
  return JSON.stringify(value, null, 2)
}

async function loadStore() {
  const source = fs.readFileSync(storePath, 'utf8')
  const outfile = path.join(os.tmpdir(), `kanji-express-content-store-${Date.now()}.mjs`)
  const result = ts.transpileModule(source, {
    compilerOptions: {
      module: ts.ModuleKind.ESNext,
      target: ts.ScriptTarget.ES2020,
      importsNotUsedAsValues: ts.ImportsNotUsedAsValues.Remove,
    },
  })
  fs.writeFileSync(outfile, result.outputText, 'utf8')
  try {
    return await import(pathToFileURL(outfile).href)
  } finally {
    fs.rmSync(outfile, { force: true })
  }
}

const store = await loadStore()
const index = {}

for (const [level, sections] of Object.entries(sectionOrderByLevel)) {
  index[level] = {}
  for (const section of sections) {
    index[level][section] = (store.LESSON_DEFS[level][section] || []).map((lesson) => ({
      title: lesson.title,
      description: lesson.description,
      mission: lesson.mission,
      canDo: lesson.canDo,
      itemCount: lesson.items.length,
    }))
  }
}

const output = `// Generated by scripts/generate-content-index.mjs. Do not edit by hand.
import type { CourseLevelId, SectionId } from './courses'

export interface LessonIndexEntry {
  title: string
  description: string
  mission?: string
  canDo?: string
  itemCount: number
}

export const LESSON_INDEX: Record<CourseLevelId, Partial<Record<SectionId, LessonIndexEntry[]>>> = ${toModuleLiteral(index)}
`

fs.writeFileSync(outPath, output, 'utf8')
